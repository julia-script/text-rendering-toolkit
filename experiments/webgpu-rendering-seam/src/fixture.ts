export interface RenderFixture {
  atlas: {
    width: number
    height: number
    cellSize: number
    pixels: Uint8Array
    distanceRange: number
  }
  instances: {
    bounds: Float32Array
    atlasSlots: Uint32Array
    colors: Uint8Array
  }
}

const INSTANCE_BOUNDS = new Float32Array([
  -1.7, 0.15, -0.95, 0.85, -0.8, 0.15, -0.05, 0.85, 0.1, 0.15, 0.85, 0.85, 1, 0.15, 1.75, 0.85,
])
const INSTANCE_SLOTS = new Uint32Array([0, 1, 2, 3])
const INSTANCE_COLORS = new Uint8Array([240, 70, 80, 80, 220, 120, 80, 140, 255, 245, 205, 75])

function decodeAtlas(): Uint8Array {
  return Uint8Array.from(atob(ATLAS_BASE64), (character) => character.charCodeAt(0))
}

export function createRenderFixture(): RenderFixture {
  const fixture = {
    atlas: {
      width: atlasFixtureMetadata.width,
      height: atlasFixtureMetadata.height,
      cellSize: atlasFixtureMetadata.cellSize,
      pixels: decodeAtlas(),
      distanceRange: atlasFixtureMetadata.distanceRange,
    },
    instances: {
      bounds: INSTANCE_BOUNDS.slice(),
      atlasSlots: INSTANCE_SLOTS.slice(),
      colors: INSTANCE_COLORS.slice(),
    },
  }
  validateRenderFixture(fixture)
  return fixture
}

export function validateRenderFixture(fixture: RenderFixture): void {
  const { atlas, instances } = fixture
  if (atlas.pixels.length !== atlas.width * atlas.height * 4) {
    throw new RangeError('atlas pixel length must equal width × height × 4')
  }
  if (
    !Number.isInteger(atlas.cellSize) ||
    atlas.cellSize <= 0 ||
    atlas.width % atlas.cellSize !== 0 ||
    atlas.height % atlas.cellSize !== 0
  ) {
    throw new RangeError('atlas cell size must be a positive integer divisor of its dimensions')
  }

  const instanceCount = instances.atlasSlots.length
  if (instances.bounds.length !== instanceCount * 4) {
    throw new RangeError('instance bounds length must equal instance count × 4')
  }
  if (instances.colors.length !== instanceCount * 3) {
    throw new RangeError('instance color length must equal instance count × 3')
  }

  for (let index = 0; index < instanceCount; index += 1) {
    const boundsOffset = index * 4
    const x0 = instances.bounds[boundsOffset]
    const y0 = instances.bounds[boundsOffset + 1]
    const x1 = instances.bounds[boundsOffset + 2]
    const y1 = instances.bounds[boundsOffset + 3]
    if (x0 === undefined || y0 === undefined || x1 === undefined || y1 === undefined) {
      throw new RangeError('instance bounds are incomplete')
    }
    if (![x0, y0, x1, y1].every(Number.isFinite) || x1 <= x0 || y1 <= y0) {
      throw new RangeError('instance bounds must be finite with positive width and height')
    }
    const slotCount = (atlas.width / atlas.cellSize) * (atlas.height / atlas.cellSize) * 4
    if ((instances.atlasSlots[index] ?? slotCount) >= slotCount) {
      throw new RangeError('atlas slot must select an available cell and RGBA channel')
    }
  }
}
